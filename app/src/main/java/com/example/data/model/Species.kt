enum class WaterType(val label: String) {
    FRESHWATER("Freshwater"),
    SALTWATER("Saltwater"),
    BRACKISH("Brackish"),
    COLDWATER_STREAM("Coldwater Stream")
}

enum class FeedingHabit(val label: String) {
    AMBUSH_COVER("Ambush / Heavy Cover"),
    ACTIVE_ROAMING_CHASER("Active Open-Water Chaser"),
    BOTTOM_SCROUNGER("Bottom Substrate Forager"),
    SUSPENDED_PELAGIC("Suspended Pelagic Roamer"),
    SURFACE_EXPLOSIVE("Surface Reaction Predator")
}

enum class BarometricSensitivity(val label: String) {
    HIGH("High (Tight to cover on high pressure)"),
    MODERATE("Moderate (Bite slows during fast changes)"),
    LOW("Low (Deep or benthic feeder, less affected)")
}

